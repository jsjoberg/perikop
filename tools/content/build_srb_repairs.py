#!/usr/bin/env python3
"""Generate text-free byte edits for known older local SRB imports.

Previous and current verses.json files remain ignored local diagnostics. The
generated header contains coordinates, checksums, deletion lengths and generic
punctuation/space/initial insertions; no Scripture or chapter-summary text.
"""
import argparse
import difflib
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def edits(previous, current):
    old = {tuple(row[:3]): row[3].encode() for row in previous}
    new = {tuple(row[:3]): row[3].encode() for row in current}
    assert len(old) == len(previous) and len(new) == len(current) and old.keys() == new.keys()
    result = []
    for key, before in old.items():
        after = new[key]
        if before == after:
            continue
        for op, start, end, a, b in reversed(difflib.SequenceMatcher(None, before, after, autojunk=False).get_opcodes()):
            if op == "equal":
                continue
            insert = after[a:b].decode()
            assert all(c in " J-" for c in insert), "Repair would distribute non-generic text"
            result.append((*key, start, end - start, insert))
            before = before[:start] + after[a:b] + before[end:]
        assert before == after, ("Invalid repair", key)
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("previous", type=Path, nargs="+")
    parser.add_argument("--current", type=Path, required=True)
    parser.add_argument("--output", type=Path, default=ROOT / "src/storage/srb2026_repairs.hpp")
    args = parser.parse_args()
    current = json.loads(args.current.read_text())
    checksums, combined = [], {}
    for index, path in enumerate(args.previous):
        previous = json.loads(path.read_text())
        checksums.append(hashlib.sha256("".join(row[3] + "\n" for row in previous).encode()).hexdigest())
        for edit in edits(previous, current):
            combined[edit] = combined.get(edit, 0) | (1 << index)
    assert len(set(checksums)) == len(checksums) and len(checksums) <= 8
    lines = ["// Generated by tools/content/build_srb_repairs.py; no Bible text.",
             "#pragma once", "#include <array>", "#include <cstddef>", "#include <string_view>",
             "", "namespace ortho {", "struct SrbTextRepair {", "    std::string_view book;",
             "    int chapter, verse;", "    std::size_t offset, erase;", "    std::string_view insert;",
             "    unsigned recipes;", "};", "",
             f"inline constexpr std::array<std::string_view, {len(checksums)}> srb_old_checksums{{{{"]
    lines.extend(f'    "{checksum}",' for checksum in checksums)
    lines.extend(["}};", "", f"inline constexpr std::array<SrbTextRepair, {len(combined)}> srb_text_repairs{{{{"])
    for edit in sorted(combined, key=lambda e: (*e[:3], -e[3])):
        book, chapter, verse, offset, erase, insert = edit
        lines.append(f'    {{"{book}", {chapter}, {verse}, {offset}, {erase}, "{insert}", {combined[edit]}}},')
    lines.extend(["}};", "} // namespace ortho", ""])
    args.output.write_text("\n".join(lines))
    print(f"{len(combined)} byte edits for {len(checksums)} known import checksums")


if __name__ == "__main__":
    main()
