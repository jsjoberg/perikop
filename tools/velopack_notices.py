#!/usr/bin/env python3
"""Write the licence notices of the Rust crates linked into Velopack's C/C++ SDK (velopack_libc).

Run it with Velopack's source at the pinned commit; cargo fetches the locked crates:

    python3 tools/velopack_notices.py <velopack source> resources/licenses/Velopack-crates.txt
"""
import argparse
import json
from pathlib import Path
import subprocess

TARGETS = ["x86_64-unknown-linux-gnu", "aarch64-unknown-linux-gnu", "x86_64-apple-darwin",
           "aarch64-apple-darwin", "x86_64-pc-windows-msvc"]
LICENCE_FILES = ("LICENSE", "LICENCE", "COPYING", "NOTICE", "UNLICENSE")


def linked(meta):
    """Packages reachable from velopack_libc through normal dependencies; build tools and macros are not linked."""
    packages = {package["id"]: package for package in meta["packages"]}
    nodes = {node["id"]: node for node in meta["resolve"]["nodes"]}
    root = next(package["id"] for package in meta["packages"] if package["name"] == "velopack_libc")
    found, pending = set(), [root]
    while pending:
        current = pending.pop()
        if current in found:
            continue
        found.add(current)
        for dependency in nodes[current]["deps"]:
            package = packages[dependency["pkg"]]
            normal = any(kind["kind"] is None for kind in dependency["dep_kinds"])
            macro = any("proc-macro" in target["kind"] for target in package["targets"])
            if normal and not macro:
                pending.append(dependency["pkg"])
    return [packages[identifier] for identifier in found]


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("source", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    crates = {}
    for target in TARGETS:
        meta = json.loads(subprocess.run(
            ["cargo", "metadata", "--locked", "--format-version", "1", "--filter-platform", target],
            cwd=args.source, check=True, capture_output=True, text=True).stdout)
        for package in linked(meta):
            crates[(package["name"], package["version"])] = package
    # Identical licence texts are written once, followed by every crate that ships them.
    texts, missing = {}, []
    for key in sorted(crates):
        package = crates[key]
        directory = Path(package["manifest_path"]).parent
        files = sorted(path for path in directory.iterdir()
                       if path.is_file() and path.name.upper().startswith(LICENCE_FILES))
        if not files:
            missing.append(package)
        for path in files:
            texts.setdefault(path.read_text(errors="replace").strip(), []).append(key)
    lines = ["Rust crates statically linked into Velopack's C/C++ SDK (velopack_libc), with their licences.",
             "Generated by tools/velopack_notices.py from Velopack's pinned Cargo.lock.", "", "Crates:", ""]
    lines += [f"- {name} {version}: {crates[(name, version)].get('license') or 'see licence file'}"
              for name, version in sorted(crates)]
    for package in missing:
        lines.append(f"  {package['name']} {package['version']} ships no licence file; its licence is "
                     f"{package.get('license')}, from {package.get('repository') or 'crates.io'}.")
    for text, owners in texts.items():
        lines += ["", "=" * 78, "Used by: " + ", ".join(f"{name} {version}" for name, version in owners), "", text]
    args.output.write_text("\n".join(lines) + "\n")
    print(f"{len(crates)} crates, {len(texts)} distinct licence texts, {len(missing)} without a licence file")


if __name__ == "__main__":
    main()
